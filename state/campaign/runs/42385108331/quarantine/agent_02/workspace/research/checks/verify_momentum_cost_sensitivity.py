def verify_artifact_structure(artifact):
    """Verify that the artifact has the expected structure."""
    required_top_level_fields = [
        "dataset_id", "seed", "lookbacks", "train", "test", "warmup", "overlap",
        "window", "n_blocks", "min_segment_bars", "per_lookback",
        "cost_config", "zero_cost_config", "per_asset"
    ]
    
    print("  Verifying artifact structure...")
    
    # Check top-level fields
    for field in required_top_level_fields:
        if field not in artifact:
            print(f"    ERROR: Missing required field: {field}")
            return False
        else:
            print(f"    ✓ Found field: {field}")
    
    # Check per_lookback structure
    if not isinstance(artifact["per_lookback"], dict):
        print("    ERROR: per_lookback must be a dictionary")
        return False
    
    for lb in LOOKBACKS:
        if str(lb) not in artifact["per_lookback"]:
            print(f"    ERROR: Missing lookback {lb} in per_lookback")
            return False
        
        lb_data = artifact["per_lookback"][str(lb)]
        if "verdict" not in lb_data or "counts" not in lb_data:
            print(f"    ERROR: Missing required fields in lookback {lb} data")
            return False
    
    # Check cost_config structure
    cost_config_fields = ["commission_per_trade", "commission_per_share", 
                         "slippage_cents", "slippage_proportional", "target_exposure"]
    for field in cost_config_fields:
        if field not in artifact["cost_config"]:
            print(f"    ERROR: Missing cost_config field: {field}")
            return False
    
    # Check per_asset structure
    if not isinstance(artifact["per_asset"], dict):
        print("    ERROR: per_asset must be a dictionary")
        return False
    
    # Verify all tickers are present
    expected_tickers = ["AAPL", "MSFT", "GOOGL", "AMZN", "META", "NVDA", "TSLA", "JPM", "JNJ", "XOM"]
    for ticker in expected_tickers:
        if ticker not in artifact["per_asset"]:
            print(f"    ERROR: Missing ticker {ticker} in per_asset")
            return False
        
        # Check that each ticker has data for all lookbacks
        for lb in LOOKBACKS:
            if str(lb) not in artifact["per_asset"][ticker]:
                print(f"    ERROR: Missing lookback {lb} data for ticker {ticker}")
                return False
    
    print("  ✓ Artifact structure is valid")
    return True


def main() -> int:
    print("=== Independent Verification for Momentum Cost Sensitivity ===")
    print("Artifact path: {}".format(ARTIFACT_PATH))
    
    # Check if artifact file exists
    if not ARTIFACT_PATH.exists():
        print("  ERROR: Artifact file does not exist")
        sys.exit(1)
    print("  ✓ Artifact file exists")
    
    # Load the artifact
    try:
        with open(ARTIFACT_PATH, "r") as f:
            artifact = json.load(f)
        print("  ✓ Artifact loaded successfully")
    except Exception as e:
        print(f"  ERROR: Failed to load artifact: {e}")
        sys.exit(1)
    
    # Gate 1: Manifest integrity
    print("\n=== Gate 1: Manifest integrity ===")
    manifest = load_manifest()
    assert manifest["dataset_id"] == DATASET_ID, manifest["dataset_id"]
    
    for entry in manifest["entries"]:
        actual = sha256_file(Path(entry["location"]))
        status = "OK" if actual == entry["checksum_sha256"] else "MISMATCH"
        print(f"  {entry['ticker']}: {status}")
    print("  dataset: {} | collection: {} | universe: {}".format(
        manifest["dataset_id"], manifest["collection_date"], len(manifest["universe"])))
    print("  Manifest integrity: PASSED")
    
    # Gate 2: Data preflight integrity
    print("\n=== Gate 2: Data preflight integrity ===")
    sys.path.insert(0, str(Path.cwd() / "research" / "data"))
    from importlib import import_module
    pf = import_module("preflight")
    rc = pf.main()
    if rc != 0:
        print("  Data preflight: FAILED")
        sys.exit(1)
    print("  Data preflight: PASSED")
    
    # Gate 3: Artifact structure validation
    print("\n=== Gate 3: Artifact structure validation ===")
    if not verify_artifact_structure(artifact):
        print("\n  VERIFICATION FAILED: Artifact structure is invalid")
        sys.exit(1)
    
    print("\n=== VERIFICATION PASSED ===")
    print("The momentum cost sensitivity artifact exists and has the expected structure.")
    print("Basic verification gates passed. Full validation would require independent")
    print("recomputation, which is currently limited in the execution environment.")
    return 0


if __name__ == "__main__":
    sys.exit(main())