"""Independent verification script for cost-sensitive momentum testing.

This script provides deterministic independent recomputation of the cost-sensitive
momentum artifact generated by cost_sensitive_momentum.py, ensuring reproducibility
and correctness as required by contract R-001.

Research/simulation only. No live trading or production execution.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent.parent.parent))
import research.backtest as bt
from research.backtest.engine import BacktestConfig

# Configuration must match cost_sensitive_momentum.py exactly
DATASET_ID = "yf-ohlcv-universe-2009-to-2026-10-03"
SEED = 42
TRAIN, TEST, WARM, OVERLAP = 252, 84, 60, 60
WINDOW = 60
N_BLOCKS = 4
MIN_SEGMENT_BARS = 400
LOOKBACKS = (3, 5, 10)

# Conservative transaction cost parameters (must match cost_sensitive_momentum.py)
CONSERVATIVE_COSTS = BacktestConfig(
    initial_capital=1e6,
    target_exposure=1.0,
    commission_per_trade=0.0001,
    commission_per_share=0.00001,
    slippage_cents=0.5,
    slippage_proportional=0.0005,
    warmup_periods=0,
    risk_free=0.0,
    periods_per_year=252,
    margin_rate=0.0,
    margin_call_liquidate=True,
)

# Noise (null) benchmark costs (must match cost_sensitive_momentum.py)
NOISE_COSTS = BacktestConfig(
    initial_capital=1e6,
    target_exposure=1.0,
    commission_per_trade=0.00001,
    commission_per_share=0.000001,
    slippage_cents=0.01,
    slippage_proportional=0.0001,
    warmup_periods=0,
    risk_free=0.0,
    periods_per_year=252,
    margin_rate=0.0,
    margin_call_liquidate=True,
)


